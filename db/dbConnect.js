const fs = require('node:fs');
const path = require('node:path');

async function connect() {
  const mysqlUrl = process.env.MYSQL_URL;
  const postgresUrl = process.env.DATABASE_URL;
  const userTable = mysqlUrl ? '`user`' : '"user"';
  let query;

  if (mysqlUrl) {
    const pool = require('mysql2/promise').createPool(mysqlUrl);
    const schema = fs.readFileSync(path.join(__dirname, 'schema.mysql.sql'), 'utf8');
    for (const sql of schema.split(';').map(part => part.trim()).filter(Boolean)) {
      await pool.query(sql);
    }
    query = async (sql, params = []) => {
      const [result] = await pool.execute(sql, params);
      return Array.isArray(result)
        ? { rows: result }
        : { changes: result.affectedRows };
    };
  } else {
    if (postgresUrl) {
      const pool = new (require('pg').Pool)({ connectionString: postgresUrl });
      query = async (sql, params = []) => {
        let position = 0;
        const result = await pool.query(sql.replaceAll('?', () => '$' + ++position), params);
        return { rows: result.rows, changes: result.rowCount };
      };
    } else {
      const { DatabaseSync } = require('node:sqlite');
      const directory = path.join(__dirname, '..', 'data');
      fs.mkdirSync(directory, { recursive: true });
      const db = new DatabaseSync(path.join(directory, 'board.sqlite'));
      query = async (sql, params = []) => {
        const statement = db.prepare(sql);
        if (sql.trimStart().startsWith('SELECT')) return { rows: statement.all(...params) };
        return { changes: statement.run(...params).changes };
      };
    }
    const idType = postgresUrl ? 'INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY' : 'INTEGER PRIMARY KEY AUTOINCREMENT';
    await query(`CREATE TABLE IF NOT EXISTS ${userTable} (
      userid VARCHAR(20) PRIMARY KEY,
      passwd VARCHAR(128) NOT NULL,
      name VARCHAR(20) NOT NULL,
      email VARCHAR(50) NOT NULL,
      reg_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
    )`);
    await query(`CREATE TABLE IF NOT EXISTS board (
      idx ${idType},
      userid VARCHAR(20) NOT NULL REFERENCES ${userTable}(userid),
      title VARCHAR(256) NOT NULL,
      content TEXT NOT NULL,
      hit INTEGER NOT NULL DEFAULT 0,
      reg_date TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
      reg_ip VARCHAR(45) NOT NULL
    )`);
  }
  return { query, userTable };
}

module.exports = connect;
